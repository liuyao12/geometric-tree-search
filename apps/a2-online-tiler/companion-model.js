import {a2Transform} from '../../assets/a2-tiling-engine.js';
import {minus,plus,tileModel} from '../../research/deterministic-a2/model.mjs';
import {tiles} from './companions.js';

const directions=[[1,0],[0,1],[-1,1],[-1,0],[0,-1],[1,-1]];
const cube=(x,y)=>[x,y,-x-y];
const big=([x,y])=>cube(BigInt(x),BigInt(y));
export function kite(h,k,s) {
  const x=2*h-2*k,y=2*h+4*k;
  const rotate=([u,v])=>{
    for(let j=0;j<s;j++) [u,v]=[-v,u+v];
    return [x+u,y+v];
  };
  return {corners:[[0,0],[2,-1],[2,0],[1,1]].map(rotate),inside:rotate([1,0])};
}

// The residue is equal precisely when the difference belongs to the
// hexagon-center translation lattice generated by (2,2) and (-2,4).
function residue([x,y]) {
  const mod=v=>Number((v%12n+12n)%12n);
  return 12*mod(4n*x+2n*y)+mod(2n*y-2n*x);
}
function species(tile) {
  const weights=new Map();
  function add([x,y],w) {
    const key=x+','+y;
    weights.set(key,[x,y,w+(weights.get(key)?.[2]??0)]);
  }
  for(const cell of tile.cells) {
    const {corners,inside}=kite(...cell);
    corners.forEach((p,j)=>add(p,[2,3,4,3][j]));
    add(inside,12);
  }
  const points=[...weights.values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
  const model=tileModel({capacity:12,points});
  const anchor=big(points[0]);
  for(const form of model.forms) {
    form.tile=tile.id;
    form.offset=plus(form.anchor,a2Transform(anchor,form.sym));
  }
  const localLoop=tile.loop.map(p=>minus(big(p),anchor));
  function pose(form,shift) {
    const p=model.pose(form,shift);
    if(!p.tile) {p.tile=tile.id; p.id=tile.id+':'+p.id;}
    return p;
  }
  return {...model,pose,localLoop,root:pose(model.forms[0],model.forms[0].offset)};
}
export function tileSet(ids) {
  const types=new Map(ids.map(id=>{
    const tile=tiles.find(t=>t.id===id);
    if(!tile) throw Error('Unknown tile '+id);
    return [id,species(tile)];
  }));
  const align=new Map(),cache=new Map();
  for(const type of types.values()) for(const form of type.forms) for(const row of form.sites) {
    const r=residue(plus(row.point,form.offset));
    if(!align.has(r)) align.set(r,[]);
    align.get(r).push({type,form,point:row.point});
  }
  function incident(q) {
    const key=String(q);
    if(!cache.has(key)) cache.set(key,(align.get(residue(q))??[]).map(a=>a.type.pose(a.form,minus(q,a.point))));
    return cache.get(key);
  }
  return {types,capacity:12n,incident,allowed:(form,shift)=>residue(minus(shift,form.offset))===0};
}
export function board(radius) {
  const targets=[];
  for(let h=-radius;h<=radius;h++) for(let k=Math.max(-radius,-radius-h);k<=Math.min(radius,radius-h);k++) {
    for(const [dx,dy] of directions) targets.push(big([2*h-2*k+dx,2*h+4*k+dy]));
  }
  return targets;
}
