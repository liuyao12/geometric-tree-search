canvas.addEventListener("pointerdown", event => { if (mode === "region" && !boundaryClosed) return; dragging = false; dragPoint = { x: event.clientX, y: event.clientY }; canvas.setPointerCapture(event.pointerId); });
canvas.addEventListener("pointermove", event => { if (!dragPoint) return; const dx = event.clientX - dragPoint.x, dy = event.clientY - dragPoint.y; if (Math.abs(dx) + Math.abs(dy) > 2) dragging = true; camera.x += dx; camera.y += dy; dragPoint = { x: event.clientX, y: event.clientY }; draw(); });
canvas.addEventListener("pointerup", event => { dragPoint = null; if (canvas.hasPointerCapture(event.pointerId)) canvas.releasePointerCapture(event.pointerId); setTimeout(() => { dragging = false; }, 0); });
canvas.addEventListener("wheel", event => { event.preventDefault(); camera.zoom = Math.max(.4, Math.min(8, camera.zoom * Math.exp(-event.deltaY * .001))); draw(); }, { passive: false });

