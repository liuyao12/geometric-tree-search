  // online tiler. It may be a hexagon or a custom shape, so learned tile-local
  // marking domains begin with the first actual placement around it.
  seed = initialLoop ? { tile: "seed", loop: initialLoop } : null;
  $("status").textContent = "Enumerating compatible placements…"; draw();
