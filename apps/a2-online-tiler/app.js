function loopIsSimple(loop) {
  if (loop.length < 3 || polygonArea2(loop) < 1e-7) return false;
  const cross = (a, b, c) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
  const onSegment = (a, b, p) => Math.abs(cross(a, b, p)) < 1e-8 && p[0] >= Math.min(a[0], b[0]) && p[0] <= Math.max(a[0], b[0]) && p[1] >= Math.min(a[1], b[1]) && p[1] <= Math.max(a[1], b[1]);
  const intersects = (a, b, c, d) => {
    const abC = cross(a, b, c), abD = cross(a, b, d), cdA = cross(c, d, a), cdB = cross(c, d, b);
    if ((abC > 0) !== (abD > 0) && (cdA > 0) !== (cdB > 0)) return true;
    return (Math.abs(abC) < 1e-8 && onSegment(a, b, c)) || (Math.abs(abD) < 1e-8 && onSegment(a, b, d)) || (Math.abs(cdA) < 1e-8 && onSegment(c, d, a)) || (Math.abs(cdB) < 1e-8 && onSegment(c, d, b));
  };
  for (let i = 0; i < loop.length; i++) for (let j = i + 1; j < loop.length; j++) {
    if (j === i + 1 || (i === 0 && j === loop.length - 1)) continue;
    const a = loop[i], b = loop[(i + 1) % loop.length], c = loop[j], d = loop[(j + 1) % loop.length];
    if (intersects(a, b, c, d)) return false;
  }
  return true;
}

const gcd = (a, b) => { a = Math.abs(a); b = Math.abs(b); while (b) [a, b] = [b, a % b]; return a || 1; };
const primitiveDirection = (a, b) => {
  const delta = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const divisor = gcd(gcd(delta[0], delta[1]), delta[2]);
  const direction = delta.map(value => value / divisor);
  const first = direction.find(value => value !== 0) || 1;
  return (first < 0 ? direction.map(value => -value) : direction).join(",");
};

function availableBoundaryDirections(tileIds) {
  const directions = new Set();
  for (const id of tileIds) {
    const loop = tileRegistry.get(id)?.loop; if (!loop) continue;
    for (const orientation of tileOrientations(id, loop)) for (let index = 0; index < orientation.loop.length; index++) directions.add(primitiveDirection(orientation.loop[index], orientation.loop[(index + 1) % orientation.loop.length]));
  }
  return directions;
}

function areaIsRepresentable(area, tileIds) {
  const units = [...new Set(tileIds.map(id => polygonArea2(tileRegistry.get(id)?.loop || [])).filter(value => Number.isInteger(value) && value > 0))];
  if (!Number.isInteger(area) || !units.length) return false;
  const reachable = new Uint8Array(area + 1); reachable[0] = 1;
  for (let value = 0; value <= area; value++) if (reachable[value]) for (const unit of units) if (value + unit <= area) reachable[value + unit] = 1;
  return !!reachable[area];
}

function cornerAngleWeights(loop) {
  const points = loop.map(([x, y]) => ({ x: x + y * 0.5, y: y * sqrt3 / 2 }));
  const signedArea = points.reduce((sum, point, index) => { const next = points[(index + 1) % points.length]; return sum + point.x * next.y - next.x * point.y; }, 0);
  const orientation = Math.sign(signedArea) || 1;
  return points.map((point, index) => {
    const previous = points[(index - 1 + points.length) % points.length], next = points[(index + 1) % points.length];
    const incoming = [point.x - previous.x, point.y - previous.y], outgoing = [next.x - point.x, next.y - point.y];
    let turn = Math.atan2(incoming[0] * outgoing[1] - incoming[1] * outgoing[0], incoming[0] * outgoing[0] + incoming[1] * outgoing[1]);
    if (orientation < 0) turn = -turn;
    let interior = Math.PI - turn; if (interior <= 0) interior += Math.PI * 2;
    return Math.round(interior * 6 / Math.PI);
  });
}

function unsupportedCornerCount(loop, tileIds) {
  const contributions = new Set([6]);
  for (const id of tileIds) for (const weight of cornerAngleWeights(tileRegistry.get(id)?.loop || [])) if (weight > 0 && weight < 12) contributions.add(weight);
  const reachable = new Uint8Array(13); reachable[0] = 1;
  for (let value = 0; value <= 12; value++) if (reachable[value]) for (const contribution of contributions) if (value + contribution <= 12) reachable[value + contribution] = 1;
  return cornerAngleWeights(loop).filter(weight => weight <= 0 || weight >= 12 || !reachable[weight]).length;
}

function isTranslationalFundamentalPolygon(loop) {
  if (![4, 6].includes(loop.length)) return false;
  const points = loop.map(axial), signs = [];
  for (let index = 0; index < points.length; index++) {
    const a = points[index], b = points[(index + 1) % points.length], c = points[(index + 2) % points.length];
    const turn = (b.x - a.x) * (c.y - b.y) - (b.y - a.y) * (c.x - b.x);
    if (Math.abs(turn) > 1e-8) signs.push(Math.sign(turn));
  }
  if (!signs.length || signs.some(sign => sign !== signs[0])) return false;
  const half = loop.length / 2;
  for (let index = 0; index < half; index++) {
    const a = loop[index], b = loop[(index + 1) % loop.length], c = loop[index + half], d = loop[(index + half + 1) % loop.length];
    if (b.some((value, axis) => value - a[axis] !== c[axis] - d[axis])) return false;
  }
  return true;
}

function assessRegion() {
  const tileIds = selectedTiles(), blockers = [], notes = [], area = polygonArea2(boundary);
  if (!boundaryClosed || !loopIsSimple(boundary)) blockers.push("Boundary must be one closed simple loop.");
  if (!areaIsRepresentable(area, tileIds)) blockers.push(`Area ${area} is not a nonnegative integer combination of ${tileIds.map(id => polygonArea2(tileRegistry.get(id)?.loop || [])).join(" and ") || "the selected tile areas"}.`);
  const directions = availableBoundaryDirections(tileIds), unsupported = boundary.filter((point, index) => !directions.has(primitiveDirection(point, boundary[(index + 1) % boundary.length]))).length;
  if (unsupported) blockers.push(`${unsupported} boundary segment${unsupported === 1 ? " uses" : "s use"} a direction unavailable on the selected tiles.`);
  const unsupportedCorners = boundary.length >= 3 ? unsupportedCornerCount(boundary, tileIds) : 0;
  if (unsupportedCorners) blockers.push(`${unsupportedCorners} boundary corner${unsupportedCorners === 1 ? " has" : "s have"} an angle that cannot be assembled from selected-tile corner contributions.`);
  if (tileIds.length === 1 && ["hat", "turtle"].includes(tileIds[0]) && isTranslationalFundamentalPolygon(boundary)) blockers.push(`A tiled ${boundary.length === 6 ? "centrally symmetric hexagon" : "parallelogram"} would repeat by translations and create a periodic ${tileRegistry.get(tileIds[0]).name} tiling.`);
  if (boundaryPreset === "certified" && tileIds.includes("turtle")) notes.push("Certified: this is the outer boundary of a verified 101-Turtle patch.");
  else if (!blockers.length) notes.push("Not ruled out, but only search can decide it. Patch, corona, and substitution-supertile boundaries are the strongest candidates.");
  return { blockers, notes, area };
}

