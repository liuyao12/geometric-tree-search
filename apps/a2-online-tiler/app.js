function boundsFor(loops) {
  const points = loops.flat().map(axial);
  if (!points.length) return { minX: -10, maxX: 10, minY: -10, maxY: 10 };
  return {
    minX: Math.min(...points.map(p => p.x)), maxX: Math.max(...points.map(p => p.x)),
    minY: Math.min(...points.map(p => p.y)), maxY: Math.max(...points.map(p => p.y))
  };
}

function makeTransform(loops, targetCanvas, useCamera = false) {
  const b = boundsFor(loops);
  const width = targetCanvas.clientWidth || targetCanvas.width;
  const height = targetCanvas.clientHeight || targetCanvas.height;
  const padding = 58;
  const fit = Math.min((width - padding * 2) / (b.maxX - b.minX || 1), (height - padding * 2) / (b.maxY - b.minY || 1));
  return point => {
    const p = axial(point);
    const baseX = padding + (p.x - b.minX) * fit;
    const baseY = padding + (p.y - b.minY) * fit;
    if (!useCamera) return { x: baseX, y: baseY };
    return {
      x: width / 2 + (baseX - width / 2) * camera.zoom + camera.x,
      y: height / 2 + (baseY - height / 2) * camera.zoom + camera.y
    };
  };
}

function drawPolygon(context, loop, transform, fill, stroke = "#23312e", width = 1.2, dashed = false) {
  if (!loop?.length) return;
  context.save();
  context.beginPath();
  loop.forEach((point, index) => {
    const p = transform(point);
    index ? context.lineTo(p.x, p.y) : context.moveTo(p.x, p.y);
  });
  context.closePath();
  if (fill) { context.fillStyle = fill; context.fill(); }
  context.strokeStyle = stroke;
  context.lineWidth = width;
  if (dashed) context.setLineDash([7, 5]);
  context.stroke();
  context.restore();
}

