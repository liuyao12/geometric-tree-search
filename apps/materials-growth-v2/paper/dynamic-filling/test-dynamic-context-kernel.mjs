import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { PointSearch, verify } = await import(pathToFileURL(process.argv[2]));
const a = { id:'a', t:[{point:'atom-a',value:6},{point:'latent',value:3}] };
const b = { id:'b', t:[{point:'atom-b',value:6},{point:'latent',value:3}] };
const model = { capacity:6, required:['atom-a','atom-b'], candidates:[a,b] };
const search = new PointSearch(model);
assert.equal(search.points.get('latent').active,false);
assert.equal(search.advance().id,'a');
assert.equal(search.points.get('latent').active,true);
assert.equal(search.points.get('latent').generation,1);
assert.equal(search.advance().id,'b');
assert.equal(search.advance().kind,'complete');
assert.equal(verify(model,['a','b'],['atom-a','atom-b','latent']).complete,true);
search.auditGraph();
const failed = new PointSearch({ ...model, candidates:[a,{id:'b',t:[{point:'atom-b',value:6}]}] });
failed.advance();
assert.equal(failed.decision().kind,'dead');
assert.equal(failed.decision().point,'latent');
assert.equal(failed.advance().kind,'exhausted');
assert.equal(failed.points.get('latent').active,false);
assert.equal(failed.placed.size,0);
failed.auditGraph();
console.log('Dormant latent activation, generation, global dead priority, full-support verification and rollback PASS');
