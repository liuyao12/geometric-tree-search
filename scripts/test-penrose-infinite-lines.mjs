import assert from 'node:assert/strict';
import {infiniteLinesCompatible,knownPenroseBenchmark} from '../assets/penrose-known-benchmark.js';
import {num,add,mul} from '../assets/penrose-polygon.js';
import {canonical} from '../assets/cyclotomic-five.js';
import {selectedPenroseProblem} from '../assets/penrose-selection-problem.js';
import {createObstructionSearch} from '../assets/cyclotomic-obstruction-search.js';
const z=canonical({coeff:[0,1,0,0],denominator:1}),p=(x,y)=>add(num(x),mul(num(y),z));
const tile=(x,bars)=>({exactPoints:[p(x,-1),p(x+1,-1),p(x+1,1),p(x,1)],bars});
const line={from:p(0,0),to:p(1,0),family:0};
const a=tile(0,[line]),b=tile(100,[{from:p(100,0),to:p(101,0),family:0}]);
assert(infiniteLinesCompatible(a,b),'coincident infinite lines match beyond their endpoints');
assert(!infiniteLinesCompatible(a,tile(100,[])),'distant tile hit is rejected without a line');
assert(!infiniteLinesCompatible(a,tile(100,[{from:p(100,1),to:p(101,1),family:0}])),'parallel displaced line is not a match');
assert(!infiniteLinesCompatible(a,tile(100,[{...b.bars[0],family:1}])),'family must agree');
const away={exactPoints:[p(100,2),p(101,2),p(101,3),p(100,3)],bars:[]};assert(infiniteLinesCompatible(a,away),'line misses polygon');
const tangent={exactPoints:[p(100,0),p(101,1),p(99,1)],bars:[]};assert(!infiniteLinesCompatible(a,tangent),'boundary tangency counts');
const vertical={from:p(50,-1),to:p(50,1),family:1};assert(infiniteLinesCompatible(a,{...away,bars:[vertical]}),'different families can cross away from tiles');
const adapter=knownPenroseBenchmark(selectedPenroseProblem());
const search=createObstructionSearch({...adapter,learn:false,targetCount:12,nodeLimit:10000});
let result,events=0;do{result=search.next();assert(++events<10000);}while(!result.done);
const s=search.snapshot();assert.equal(s.tiles.length,12);assert(!s.learning);
const neighbor=s.tiles.slice(1).find(t=>[...t.signatures.keys()].some(e=>s.tiles[0].signatures.has(e)));assert(neighbor);
const relabeled={...neighbor,signatures:new Map([...neighbor.signatures].map(([e])=>[e,'deliberately different']))};
assert(adapter.problem.pairAllowed(s.tiles[0],relabeled),'Ammann geometry does not secretly check edge labels');
for(const t of s.tiles)for(const u of s.tiles)assert(adapter.extraAllowed(t,u));
console.log('ok: exact infinite lines, distant contacts, offsets, families, tangencies, and 12-tile line-only search');
