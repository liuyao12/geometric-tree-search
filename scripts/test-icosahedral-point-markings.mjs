import assert from 'node:assert/strict';
import { PointMarkingState,markingValueKey } from '../assets/exact-point-marking-state.js';
import { vector } from '../assets/golden-field.js';
const trail=[];
const set=(map,key,value)=>{const had=map.has(key),old=map.get(key);trail.push(()=>had?map.set(key,old):map.delete(key));map.set(key,value);};
const add=(s,key)=>{if(s.has(key))return;trail.push(()=>s.delete(key));s.add(key);};
const undo=n=>{while(trail.length>n)trail.pop()();};
const state=new PointMarkingState({set,add}),far=vector(10000n,20000n,30000n);
const a={id:'a',pointMarkings:[{point:far,components:{channel:0}}]},b={id:'b',pointMarkings:[{point:far,components:{channel:1}}]},free={id:'free',pointMarkings:[{point:far,components:{other:0}}]};
state.register(a);state.register(b);state.register(free);
const before=state.inspect(),checkpoint=trail.length;
state.assign(a);assert.equal(state.pointCount,1);assert.equal(state.componentCount,1);
assert(!state.compatible(b));assert(state.compatible(free));assert(state.compatible(a));
assert.deepEqual(new Set(state.affected(a)),new Set(['a','b','free']),'Dependencies include far marking-only support without spatial bounds');
state.assign(a);assert.equal(state.inspect().values[0][1][0][2],2);
assert.throws(()=>state.assign(b),/Conflicting/);undo(checkpoint);assert.deepEqual(state.inspect(),before);
assert.equal(markingValueKey(0),markingValueKey(0n));assert.throws(()=>markingValueKey(0.1),TypeError);
assert.notEqual(markingValueKey(['a|integer:1']),markingValueKey(['a',1]));
state.assign(free);assert(state.compatible(a),'Missing components are unconstrained');
console.log('ok: exact point m-values; assigned zero versus missing; reference counts; complete rollback; far marking-only dependencies');
